    JOIN par_equ l ON l.partido_id_partido = p.id_partido AND l.rol = 'LOCAL' WHERE p.estado = 'FINALIZADO' AND p.torneo_id_torneo = 1
  UNION ALL
  SELECT v.equ_tor_id_equipo, p.goles_visitante, p.goles_local FROM partido p
    JOIN par_equ v ON v.partido_id_partido = p.id_partido AND v.rol = 'VISITANTE' WHERE p.estado = 'FINALIZADO' AND p.torneo_id_torneo = 1
),
tabla AS (
  SELECT g.letra AS grupo, e.id_equipo, e.nombre,
         COUNT(*) AS pj, SUM(r.gf > r.gc) AS pg, SUM(r.gf = r.gc) AS pe, SUM(r.gf < r.gc) AS pp,
         SUM(r.gf) AS gf, SUM(r.gc) AS gc, SUM(r.gf) - SUM(r.gc) AS dg,
         SUM(CASE WHEN r.gf > r.gc THEN 3 WHEN r.gf = r.gc THEN 1 ELSE 0 END) AS pts
  FROM res r
  JOIN equ_gru eg ON eg.equ_tor_equipo_id_equipo = r.eq AND eg.grupo_id_torneo = 1
  JOIN grupo g ON g.id_grupo = eg.grupo_id_grupo AND g.torneo_id_torneo = 1
  JOIN equipo e ON e.id_equipo = r.eq
  GROUP BY g.letra, e.id_equipo, e.nombre
),
pos AS (
  SELECT t.*, ROW_NUMBER() OVER (PARTITION BY grupo ORDER BY pts DESC, dg DESC, gf DESC, nombre) AS puesto FROM tabla t
)
SELECT grupo, puesto, nombre AS equipo, pj, pg, pe, pp, gf, gc, dg, pts,
  CASE WHEN puesto <= 2 THEN 'CLASIFICA' WHEN puesto = 3 THEN 'Mejor tercero?' ELSE 'Eliminado' END AS situacion
FROM pos ORDER BY grupo, puesto;

