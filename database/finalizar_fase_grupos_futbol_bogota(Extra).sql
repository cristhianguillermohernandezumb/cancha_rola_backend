tabla AS (
  SELECT g.letra AS grupo, e.id_equipo, e.nombre,
         COUNT(*) AS pj, SUM(r.gf > r.gc) AS pg, SUM(r.gf = r.gc) AS pe, SUM(r.gf < r.gc) AS pp,
         SUM(r.gf) AS gf, SUM(r.gc) AS gc, SUM(r.gf) - SUM(r.gc) AS dg,
         SUM(CASE WHEN r.gf > r.gc THEN 3 WHEN r.gf = r.gc THEN 1 ELSE 0 END) AS pts
  FROM res r
  JOIN equ_gru eg ON eg.equ_tor_equipo_id_equipo = r.eq AND eg.grupo_id_torneo = 1
  JOIN grupo g ON g.id_grupo = eg.grupo_id_grupo AND g.torneo_id_torneo = 1
  JOIN equipo e ON e.id_equipo = r.eq
  GROUP BY g.letra, e.id_equipo, e.nombre
),
pos AS (
  SELECT t.*, ROW_NUMBER() OVER (PARTITION BY grupo ORDER BY pts DESC, dg DESC, gf DESC, nombre) AS puesto FROM tabla t
),
terceros AS (
  SELECT p.*, ROW_NUMBER() OVER (ORDER BY pts DESC, dg DESC, gf DESC, nombre) AS rank_tercero FROM pos p WHERE puesto = 3
)
SELECT grupo, puesto, nombre AS equipo, pts, dg, gf, 'Primero/segundo de grupo' AS clasifico_como FROM pos WHERE puesto <= 2
UNION ALL
SELECT grupo, puesto, nombre, pts, dg, gf, CONCAT('Mejor tercero #', rank_tercero) FROM terceros WHERE rank_tercero <= 8
ORDER BY puesto, pts DESC, dg DESC, gf DESC, equipo;

-- 3) Goleadores de la fase de grupos
SELECT j.primer_nombre, j.primer_apellido, eq.nombre AS equipo, COUNT(*) AS goles
FROM evento_partido e JOIN jugador j ON j.id_jugador = e.alineacion_id_jugador JOIN equipo eq ON eq.id_equipo = e.alineacion_id_equipo
WHERE e.tipo_evento = 'GOL' GROUP BY j.id_jugador, j.primer_nombre, j.primer_apellido, eq.nombre
ORDER BY goles DESC, j.primer_apellido LIMIT 10;
